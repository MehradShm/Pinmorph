import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

test('business products, Shop, analytic rollups and clearly separate ad placeholders', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const stamp = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  const email = `browser-${stamp}@example.test`;
  const signup = await page.request.post('/api/auth/signup', { data: { email, display_name: 'Shop creator', password: 'browser-password-123' } });
  expect(signup.status()).toBe(201);
  const account = await signup.json();
  const artifact = test.info().outputPath('account.json');
  mkdirSync(dirname(artifact), { recursive: true }); writeFileSync(artifact, JSON.stringify({ id: account.id, email }));
  // Distinct pixels avoid cross-test duplicate suppression while still exercising real CLIP.
  const png = execFileSync('../.venv/bin/python', ['-c', 'import hashlib,io,sys; from PIL import Image; s=io.BytesIO(); Image.new("RGB",(80,120),tuple(hashlib.sha256(sys.argv[1].encode()).digest()[:3])).save(s,"PNG"); sys.stdout.buffer.write(s.getvalue())', stamp]);
  const title = `shopfixture${stamp.replaceAll('-', '')}`;
  const upload = await page.request.post('/api/pins', { multipart: { title, image: { name: 'shop.png', mimeType: 'image/png', buffer: png } } });
  expect(upload.status(), await upload.text()).toBe(202);
  const pin = await upload.json();
  await expect.poll(async () => (await (await page.request.get(`/api/pins/${pin.id}`)).json()).status, { timeout: 40_000 }).toBe('ready');
  await page.goto('/');
  await page.getByRole('button', { name: 'Business', exact: true }).click();
  await page.getByLabel('Business name', { exact: true }).fill('Garden studio');
  await page.getByLabel('Business website', { exact: true }).fill('https://shop.example.test');
  await page.getByRole('button', { name: 'Enable business account' }).click();
  await expect(page.getByRole('heading', { name: 'Your pin activity' })).toBeVisible();
  await page.getByRole('button', { name: 'Uploads', exact: true }).click();
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).click();
  await page.getByRole('button', { name: 'Add product details' }).click();
  const editor = page.getByRole('dialog', { name: 'Product details', exact: true });
  await editor.getByLabel('Price', { exact: true }).fill('29.90');
  await editor.getByLabel('Currency', { exact: true }).selectOption('CAD');
  await editor.getByLabel('Shop link', { exact: true }).fill('https://shop.example.test/item');
  await editor.getByRole('button', { name: 'Save product', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Visit shop' })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true }).getByText(/29\.90/)).toBeVisible();
  await page.getByRole('button', { name: 'Shop', exact: true }).click();
  await page.getByLabel('Search products', { exact: true }).fill(title);
  await page.getByLabel('Product currency', { exact: true }).selectOption('CAD');
  await page.getByRole('button', { name: 'Find products', exact: true }).click();
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).scrollIntoViewIfNeeded();
  await expect.poll(async () => {
    const report = await page.request.post('/api/business/analytics/refresh');
    expect(report.status()).toBe(200);
    return (await (await page.request.get('/api/business/analytics')).json()).totals.impressions;
  }, { timeout: 10_000 }).toBeGreaterThan(0);
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).click();
  await page.context().route('https://shop.example.test/**', route => route.fulfill({ status: 200, body: 'Local shop link test' }));
  const popupReady = page.waitForEvent('popup');
  await page.getByRole('link', { name: 'Visit shop' }).click();
  const popup = await popupReady; await popup.close();
  await page.getByRole('button', { name: 'Edit product details' }).click();
  const update = page.getByRole('dialog', { name: 'Product details', exact: true });
  await update.getByLabel('Availability', { exact: true }).selectOption('out_of_stock');
  await update.getByRole('button', { name: 'Save product', exact: true }).click();
  await expect(update).not.toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Shop', exact: true }).click();
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Business', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh analytics' }).click();
  await expect(page.getByTestId('total-outbound_clicks')).toHaveText('1');
  await expect(page.getByTestId('total-impressions')).not.toHaveText('0');
  await page.getByLabel('Traffic', { exact: true }).selectOption('simulator');
  await expect(page.getByTestId('total-impressions')).toHaveText('0');
  await page.getByRole('button', { name: 'Discover', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'Advertisement placeholder' })).toHaveCount(2);
  await expect(page.locator('.ad-placeholder .pin-card')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
  await page.screenshot({ path: `test-results/phase5-${test.info().project.name}.png`, fullPage: true });
});
