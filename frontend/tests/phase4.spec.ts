import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

import { png } from './fixtures';

test('keyword search, profile editing, private boards, sections, follows and activity', async ({ page, browser, baseURL }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const stamp = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  const name = `Collector ${stamp}`;
  const email = `browser-${stamp}@example.test`;
  const accountResponse = await page.request.post('/api/auth/signup', { data: { email, display_name: name, password: 'browser-password-123' } });
  expect(accountResponse.status()).toBe(201);
  const account = await accountResponse.json();
  const artifact = test.info().outputPath('account.json');
  mkdirSync(dirname(artifact), { recursive: true }); writeFileSync(artifact, JSON.stringify({ id: account.id, email }));
  const word = `blossom${Math.random().toString(36).slice(2)}`;
  const title = `${word} garden`;
  const upload = await page.request.post('/api/pins', { multipart: { title, image: { name: 'garden.png', mimeType: 'image/png', buffer: png } } });
  expect(upload.status(), await upload.text()).toBe(202);
  const pin = await upload.json();
  await expect.poll(async () => (await (await page.request.get(`/api/pins/${pin.id}`)).json()).status, { timeout: 30_000 }).toBe('ready');
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  await page.getByLabel('Search pins').fill(word);
  await page.getByLabel('Collection', { exact: true }).selectOption('manual_upload');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true })).toBeVisible();
  await expect(page.locator('.pin-card')).toHaveCount(1);
  await page.getByRole('button', { name: `Open ${title}`, exact: true }).click();
  await page.getByRole('button', { name: '+ Create a board' }).click();
  const boardDialog = page.getByRole('dialog', { name: 'Create a board', exact: true });
  await boardDialog.getByLabel('Board name').fill('Garden ideas');
  await expect(boardDialog.getByLabel('Keep this board secret')).toBeChecked();
  await boardDialog.getByRole('button', { name: 'Create board', exact: true }).click();
  await page.getByRole('button', { name: 'Save pin', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Saved to Garden ideas');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'My boards', exact: true }).click();
  await page.getByRole('button', { name: /Garden ideas/ }).click();
  await page.getByLabel('New section').fill('Plants');
  await page.getByRole('button', { name: 'Add section', exact: true }).click();
  await expect(page.getByLabel(`Move ${title} to section`)).toBeVisible();
  await page.getByLabel(`Move ${title} to section`).selectOption({ label: 'Plants' });
  await page.getByLabel('Board section').selectOption({ label: 'Plants' });
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete section', exact: true }).click();
  await expect(page.getByLabel('Board section')).toHaveValue('');
  await expect(page.getByRole('button', { name: `Open ${title}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Make public', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Make secret', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'My profile', exact: true }).click();
  const profile = page.getByRole('dialog', { name, exact: true });
  await profile.getByRole('button', { name: 'Edit profile', exact: true }).click();
  await profile.getByLabel('About you').fill('Collecting gardens.');
  await profile.getByRole('button', { name: 'Save profile', exact: true }).click();
  await expect(profile.getByText('Collecting gardens.', { exact: true })).toBeVisible();
  await profile.getByRole('tab', { name: 'Created pins', exact: true }).click();
  await expect(profile.getByRole('button', { name: `Created ${title}`, exact: true })).toBeVisible();
  await profile.getByRole('tab', { name: 'Boards', exact: true }).click();
  await profile.getByRole('button', { name: 'Close dialog' }).click();

  const guest = await browser.newContext({ baseURL });
  try {
    const stamp2 = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
    const email2 = `browser-${stamp2}@example.test`;
    const response = await guest.request.post('/api/auth/signup', { data: { email: email2, display_name: 'Another collector', password: 'browser-password-123' } });
    expect(response.status()).toBe(201);
    const account2 = await response.json();
    const artifact2 = test.info().outputPath('other/account.json');
    mkdirSync(dirname(artifact2), { recursive: true }); writeFileSync(artifact2, JSON.stringify({ id: account2.id, email: email2 }));
    const other = await guest.newPage();
    await other.goto('/');
    await other.getByRole('button', { name: 'People', exact: true }).click();
    await other.getByLabel('Search people').fill(name);
    await other.getByRole('button', { name: 'Find people', exact: true }).click();
    await other.getByRole('button', { name: new RegExp(name) }).click();
    const otherProfile = other.getByRole('dialog', { name, exact: true });
    await otherProfile.getByRole('button', { name: 'Follow', exact: true }).click();
    await expect(otherProfile.getByRole('button', { name: 'Unfollow', exact: true })).toBeVisible();
    await otherProfile.getByRole('button', { name: 'Garden ideas', exact: true }).click();
    await other.getByRole('button', { name: 'Follow board', exact: true }).click();
    await expect(other.getByRole('button', { name: 'Unfollow board', exact: true })).toBeVisible();
    await expect(other.getByRole('button', { name: `Remove ${title} from board` })).toHaveCount(0);
    await page.getByRole('button', { name: 'Activity', exact: true }).click();
    await expect(page.getByText('followed you', { exact: true })).toBeVisible();
    await expect(page.getByText('followed your board', { exact: true })).toBeVisible();
    expect(await other.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  } finally { await guest.close(); }
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `test-results/phase4-${test.info().project.name}.png`, fullPage: true });
});
